    pub fn score(input: &[f64]) -> [f64; 2] {
        if input.len() < Self::N {
            return [0.5, 0.5];
        }

        let hp = input[7];
        let sim_lethal = input[36];
        let speed = input[12];
        let void_dist = input[3];
        let y = input[1];
        let explosive = input[15];
        let combat_sec = input[22];
        let mobs_atk = input[11];
        let dmg_taken = input[21];
        let threat_dps = input[17];

        if hp <= 1.0
            || sim_lethal >= 0.95
            || (speed >= 1.5 && hp < 12.0)
            || (explosive >= 0.5 && hp < 8.0)
            || (explosive >= 0.5 && combat_sec >= 1.0)
            || (void_dist <= 1.0 && y < 10.0)
            || (input[34] >= 0.5 && mobs_atk >= 1.0)
        {
            return [1.0, 0.0];
        }

        if combat_sec == 0.0
            && mobs_atk == 0.0
            && dmg_taken == 0.0
            && threat_dps == 0.0
            && explosive < 0.5
            && speed < 0.15
            && hp >= 18.0
            && input[33] == 0.0
            && input[27] == 0.0
            && input[28] == 0.0
        {
            return [0.0, 1.0];
        }

        let mut dread = 0.0;
        let mut hope = 0.0;
        for i in 0..Self::N {
            let s = Self::SIGN[i];
            if s == 0 {
                continue;
            }
            let z = ((input[i] - Self::BASELINE[i]) / Self::SCALE[i] * f64::from(s)).clamp(-6.0, 6.0);
            if z > 0.0 {
                dread += z;
            } else {
                hope += -z;
            }
        }

        let mut worst_memory = 0.0f64;
        for m in &Self::MEMORIES {
            let mut d2 = 0.0;
            for i in 0..Self::N {
                if Self::SIGN[i] == 0 {
                    continue;
                }
                let dx = (input[i] - m[i]) / Self::SCALE[i];
                d2 += dx * dx;
            }
            let sim = (-d2 / Self::RBF_BANDWIDTH).exp();
            if sim > worst_memory {
                worst_memory = sim;
            }
        }

        let mut dim_adj = 0.0;
        let dim = input[0];
        if dim < -0.5 {
            dim_adj -= 0.30;
        } else if dim > 0.5 {
            dim_adj -= 0.40 - 0.30 * input[6];
        }
        if input[5] >= 0.5 {
            dim_adj -= 0.10;
        }

        let logit = Self::W_HOPE * hope - Self::W_DREAD * dread - Self::W_MEMORY * worst_memory
            + dim_adj
            + Self::LOGIT_BIAS;
        let p_safe = (1.0 / (1.0 + (-logit).exp())).clamp(0.0, 1.0);
        [1.0 - p_safe, p_safe]
    }
